    private fun MutableList<DailyQuote>.addCategory(
        category: QuoteCategory,
        vararg texts: String,
    ) {
        texts.forEachIndexed { index, text ->
            add(
                DailyQuote(
                    id = "${category.name.lowercase()}-${(index + 1).toString().padStart(2, '0')}",
                    text = text,
                    category = category,
                ),
            )
        }
    }
